function openClass(cls){
  document.getElementById("modalTitle").textContent = "COC " + cls;
  const days = document.getElementById("days");
  days.innerHTML = "";
  Object.entries(schedules[cls]).forEach(([day, rows])=>{
    const box=document.createElement("div");
    box.className="day";
    box.innerHTML=`<h3>${day}</h3><table><thead><tr><th>الحصة</th><th>الموعد</th></tr></thead><tbody>${rows.map(r=>`<tr><td>${r[0]}</td><td>${r[1]}</td></tr>`).join("")}</tbody></table>`;
    days.appendChild(box);
  });
  const modal=document.getElementById("classModal");
  modal.classList.add("show");
  modal.setAttribute("aria-hidden","false");
}
function closeClass(){
  const modal=document.getElementById("classModal");
  modal.classList.remove("show");
  modal.setAttribute("aria-hidden","true");
}
document.getElementById("classModal").addEventListener("click",e=>{
  if(e.target.id==="classModal") closeClass();
});
document.addEventListener("keydown",e=>{if(e.key==="Escape") closeClass()});
